#!/usr/bin/env python3
"""Generates widths.km and widths.c (the stdint reference) from one table.
Run: python3 tests/widths/gen.py   (outputs next to this file)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
TYPES = {  # name: (bits, signed, ctype, vals)
    "u8": (8, False, "uint8_t", [0, 1, 2, 127, 128, 200, 254, 255]),
    "u16": (16, False, "uint16_t", [0, 1, 255, 256, 32767, 32768, 65534, 65535]),
    "u32": (32, False, "uint32_t", [0, 1, 65535, 2147483647, 2147483648, 4294967294, 4294967295]),
    "u64": (64, False, "uint64_t", [0, 1, 4294967296, 9223372036854775807, 9223372036854775808, 18446744073709551614, 18446744073709551615]),
    "i8": (8, True, "int8_t", [-128, -127, -2, -1, 0, 1, 126, 127]),
    "i16": (16, True, "int16_t", [-32768, -32767, -1, 0, 1, 255, 32766, 32767]),
    "i32": (32, True, "int32_t", [-2147483648, -2147483647, -1, 0, 1, 65536, 2147483646, 2147483647]),
}
km = ["// generated by tests/widths/gen.py -- do not edit", ""]
c = ["// generated by tests/widths/gen.py -- do not edit", "#include <stdio.h>", "#include <stdint.h>", "#include <stdlib.h>", "#include <string.h>",
     "static void fmtf(float f){ char b[64]; int p=1; for(;p<9;p++){ snprintf(b,64,\"%.*e\",p-1,(double)f); if((float)strtod(b,0)==f) break; }",
     "  snprintf(b,64,\"%.*g\",p<6?6:p,(double)f); if(!strpbrk(b,\".eEni\")) strcat(b,\".0\"); puts(b); }",
     "static void fmtd(double d){ char b[64]; snprintf(b,64,\"%g\",d); if(!strpbrk(b,\".eEni\")) strcat(b,\".0\"); puts(b); }",
     "#define PS(x) printf(\"%lld\\n\",(long long)(x))",
     "#define PU(x) printf(\"%llu\\n\",(unsigned long long)(x))",
     "#define PB(x) puts((x)?\"1\":\"0\")", ""]
def lit(v, t):
    return str(v) if v >= 0 else str(v)
def clit(v, t):
    if v == -2**63: return "(-9223372036854775807LL-1)"
    if t == "i32" and v == -2**31: return "(-2147483647-1)"
    return str(v) + ("ULL" if v > 2**63 - 1 else "LL" if abs(v) > 2**31 else "")
for t, (bits, sg, ct, vals) in TYPES.items():
    P = "PS" if sg else "PU"
    km += [f"void t_{t}()", f"    let vs: [{t}] = [" + ", ".join(lit(v, t) for v in vals) + "]"]
    c += [f"static void t_{t}(void) {{", f"  {ct} vs[] = {{" + ", ".join(clit(v, t) for v in vals) + "};", f"  for (int i = 0; i < {len(vals)}; i++) for (int j = 0; j < {len(vals)}; j++) {{", f"    {ct} a = vs[i], b = vs[j];"]
    km += ["    for a in vs do", "        for b in vs do"]
    ind = "            "
    ops = [("a + b", f"{P}(({ct})((uint64_t)a + (uint64_t)b))"), ("a - b", f"{P}(({ct})((uint64_t)a - (uint64_t)b))"),
           ("a * b", f"{P}(({ct})((uint64_t)a * (uint64_t)b))"), ("a & b", f"{P}(({ct})(a & b))"), ("a | b", f"{P}(({ct})(a | b))"),
           ("a ^ b", f"{P}(({ct})(a ^ b))"), ("-a", f"{P}(({ct})(0 - (uint64_t)a))"),
           ("a << 3", f"{P}(({ct})((uint64_t)a << 3))"), ("a >> 2", f"{P}(({ct})(a >> 2))"),
           ("a << (b & 3)", f"{P}(({ct})((uint64_t)a << (b & 3)))"), ("a >> (b & 3)", f"{P}(({ct})(a >> (b & 3)))")]
    for k, cc in ops:
        km.append(f"{ind}print({k})"); c.append("    " + cc + ";")
    for o in ["<", "<=", ">", ">=", "==", "!="]:
        km.append(f"{ind}print(a {o} b)"); c.append(f"    PB(a {o} b);")
    km += [f"{ind}let w = a", f"{ind}w += b", f"{ind}print(w)", f"{ind}w *= b", f"{ind}print(w)", f"{ind}w -= a", f"{ind}print(w)", f"{ind}w <<= 1" if False else f"{ind}w = w + 1", f"{ind}print(w)"]
    c += [f"    {ct} w = a; w = ({ct})((uint64_t)w + (uint64_t)b); {P}(w); w = ({ct})((uint64_t)w * (uint64_t)b); {P}(w); w = ({ct})((uint64_t)w - (uint64_t)a); {P}(w); w = ({ct})((uint64_t)w + 1); {P}(w);"]
    guard = "b != 0"
    cg = "b != 0"
    if sg:
        guard += f" and not (b == -1)"
        cg += " && b != -1"
    km += [f"{ind}if {guard} then", f"{ind}    print(a / b)", f"{ind}    print(a % b)"]
    c += [f"    if ({cg}) {{ {P}(({ct})(a / b)); {P}(({ct})(a % b)); }}"]
    c += ["  }", "}", ""]
    km.append("")
    # string(x) + a wrapping loop counter
    km += [f"void l_{t}()", f"    let c: {t} = {vals[-1]}", "    let n = 0", "    while n < 6 do", "        print(string(c))", "        c += 1", "        n += 1", ""]
    c += [f"static void l_{t}(void) {{ {ct} c = {clit(vals[-1], t)}; for (int n = 0; n < 6; n++) {{ char b[32]; snprintf(b, 32, \"%{'lld' if sg else 'llu'}\", ({'long long' if sg else 'unsigned long long'})c); puts(b); c = ({ct})((uint64_t)c + 1); }} }}", ""]
# conversions
names = list(TYPES)
km += ["void conv()"]
c += ["static void conv(void) {"]
for s in names:
    sb, ssg, sct, svals = TYPES[s]
    km += [f"    let v_{s}: [{s}] = [" + ", ".join(lit(v, s) for v in svals) + "]"]
    c += [f"  {{ {sct} v[] = {{" + ", ".join(clit(v, s) for v in svals) + "};"]
    for d in names:
        if d == s: continue
        db, dsg, dct, _ = TYPES[d]
        P = "PS" if dsg else "PU"
        km += [f"    for x in v_{s} do", f"        print({d}(x))"]
        c += [f"    for (int i = 0; i < {len(svals)}; i++) {P}(({dct})v[i]);"]
    c += ["  }"]
km += ["    let f1: float = 3.9", "    print(u8(f1))", "    print(i16(f1))", "    print(u32(f1 * 1000.0))", "    print(i32(0.0 - f1))",
       "    let u: u64 = 18446744073709551615", "    let fu: float = u", "    print(fu)", "    let i1: i32 = -5", "    let fi: float = i1", "    print(fi)",
       "    let q: u32 = 4000000000", "    let p: u8 = 200", "    print(q + p)", "    print(p * 2 + q)",
       "    let r: i16 = -3", "    let z: i32 = 70000", "    print(z * r)", ""]
c += ["  { double f1 = 3.9; PU((uint8_t)f1); PS((int16_t)f1); PU((uint32_t)(f1 * 1000.0)); PS((int32_t)(0.0 - f1));",
      "    uint64_t u = 18446744073709551615ULL; fmtd((double)u); int32_t i1 = -5; fmtd((double)i1);",
      "    uint32_t q = 4000000000u; uint8_t p = 200; PU((uint32_t)(q + p)); PU((uint32_t)((uint8_t)(p * 2) + q));",
      "    int16_t r = -3; int32_t z = 70000; PS((int32_t)(z * r)); } }", ""]
# f32
km += ["void t_f32()", "    let s: f32 = 0.0", "    let i = 0", "    while i < 1000 do", "        s += 0.1", "        i += 1", "    print(s)",
       "    let x: f32 = 16777216.0", "    print(x + 1.0)", "    let y: f32 = 1.0", "    y = y / 3.0", "    print(y)", "    print(y * 3.0)",
       "    let z: f32 = 0.1", "    print(z + 0.2)", "    print(z * z)", "    print(f32(1) / f32(3))", "    let big: f32 = 1000000.0", "    print(big * big)",
       "    let m: f32 = 0.0", "    for k = 1 until 11", "        m += 1.0 / 3.0", "    print(m)", "    print(string(z))", ""]
c += ["static void t_f32(void) { float s = 0.0f; for (int i = 0; i < 1000; i++) s += 0.1f; fmtf(s);",
      "  float x = 16777216.0f; fmtf(x + 1.0f); float y = 1.0f; y = y / 3.0f; fmtf(y); fmtf(y * 3.0f);",
      "  float z = 0.1f; fmtf(z + 0.2f); fmtf(z * z); fmtf((float)1 / (float)3); float big = 1000000.0f; fmtf(big * big);",
      "  float m = 0.0f; for (int k = 1; k < 11; k++) m += 1.0f / 3.0f; fmtf(m); fmtf(z); }", ""]
km += ["void main()"] + [f"    t_{t}()\n    l_{t}()" for t in names] + ["    conv()", "    t_f32()"]
c += ["int main(void) {"] + [f"  t_{t}(); l_{t}();" for t in names] + ["  conv(); t_f32(); return 0; }"]
open(os.path.join(here, "widths.km"), "w").write("\n".join(km) + "\n")
open(os.path.join(here, "widths.c"), "w").write("\n".join(c) + "\n")
