#!/usr/bin/env python3
"""gen-diag — build the diagnostics catalog from its single source.

    tools/gen-diag.py            regenerate (writes the files below)
    tools/gen-diag.py --check    exit 1 when the generated files are stale

Input:   docs/errors/catalog.txt     (format described at the top of that file)
Output:  modules/support/diag_catalog.kmm   the table the compiler's renderer reads
         docs/errors/K0001.md ...           one `komodo explain` page per code
         docs/errors/README.md              the index
"""
import re, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / 'docs/errors/catalog.txt'


def parse():
    ents, cur, blk = [], None, None
    for raw in src.read_text().split('\n'):
        if raw.startswith('#') and cur is None:
            continue
        m = re.match(r'@ (K\d{4})\s*(.*)$', raw)
        if m:
            cur = {'code': m.group(1), 'title': m.group(2), 'files': {}}
            ents.append(cur); blk = None
            continue
        if cur is None:
            continue
        if blk is not None and (raw.startswith('  ') or raw == ''):
            blk.append(raw[2:])
            continue
        blk = None
        m = re.match(r'(bad|fix):\s*$', raw)
        if m:
            blk = cur.setdefault(m.group(1), []); continue
        m = re.match(r'file (\S+):\s*$', raw)
        if m:
            blk = cur['files'].setdefault(m.group(1), []); continue
        m = re.match(r'(match|why|help|span|mode|note):\s*(.*)$', raw)
        if m:
            cur[m.group(1)] = m.group(2)
    for e in ents:
        for k in ('bad', 'fix'):
            if k in e:
                while e[k] and e[k][-1] == '':
                    e[k].pop()
        for f in e['files'].values():
            while f and f[-1] == '':
                f.pop()
    return ents


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def kmm(ents):
    out = ['module km_compiler', '',
           '// GENERATED by tools/gen-diag.py from docs/errors/catalog.txt — do not edit.',
           '// One entry per diagnostic: code, message pattern (`*` = any text), why, help, span.',
           '', 'fn diagCatalog(): [string]', '    let c: [string] = []']
    for e in ents:
        f = [e['code'], e['match'], e.get('why', ''), e.get('help', ''), e.get('span', '')]
        out.append('    c += ["' + '\\t'.join(esc(x) for x in f) + '"]')
    out += ['    return c', '']
    return '\n'.join(out)


def page(e):
    t = ['# ' + e['code'] + ': ' + e['title'], '',
         'Message: `' + e['match'].replace('*', '…') + '`', '',
         '## What went wrong', '', re.sub(r'\{\d\}', '…', e.get('why', '')), '']
    if e.get('help'):
        t += ['**How to fix it:** ' + re.sub(r'\{\d\}', '…', e['help']), '']
    if 'bad' in e:
        strict = e.get('mode') == 'strict'
        text = '\n'.join(e['bad'] + e.get('fix', []))
        # examples that cannot link on their own (C symbols, no main) are only compiled by tests/diag
        multi = bool(e['files']) or 'extern ' in text or 'export ' in text or 'void main' not in text
        t += ['## Example', '']
        for n, body in e['files'].items():
            t += ['File `' + n + '`:', '', '<!-- doc-skip -->', '```km'] + body + ['```', '']
        if strict or multi:
            t += ['<!-- doc-skip -->']
            if strict:
                t += ['Compile with `komodo --strict`.', '']
        else:
            t += ['<!-- doc-error -->']
        t += ['```km'] + e['bad'] + ['```', '']
        if 'fix' in e:
            t += ['## Fixed', '']
            if strict or multi:
                t += ['<!-- doc-skip -->']
            t += ['```km'] + e['fix'] + ['```', '']
    if e.get('note'):
        t += [e['note'], '']
    return '\n'.join(t)


def index(ents):
    t = ['# Compiler error codes', '',
         'Every diagnostic the compiler prints in the rich layout carries a code.',
         'Run `komodo explain K0001` for the long form. See [diagnostics](../diagnostics.md).', '',
         '| Code | Message |', '|---|---|']
    for e in ents:
        t.append('| [%s](%s.md) | `%s` |' % (e['code'], e['code'], e['match'].replace('*', '…').replace('|', '\\|')))
    return '\n'.join(t) + '\n'


def main():
    check = '--check' in sys.argv[1:]
    ents = parse()
    outputs = {root / 'modules/support/diag_catalog.kmm': kmm(ents), root / 'docs/errors/README.md': index(ents)}
    for e in ents:
        outputs[root / 'docs/errors' / (e['code'] + '.md')] = page(e).rstrip('\n') + '\n'
    stale = 0
    for p, text in outputs.items():
        if p.exists() and p.read_text() == text:
            continue
        stale += 1
        if not check:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    if check:
        sys.exit(1 if stale else 0)
    print('catalog: %d entries, %d files written' % (len(ents), stale))


if __name__ == '__main__':
    main()
